// Affiche un résumé lisible de chaque analyse sur les données de démonstration (vérification humaine, hors tests).
process.env.NODE_ENV = 'test';
const { buildApp } = await import('../src/app.js');
const { DEMO } = await import('../src/db/seed.js');
const { pool } = await import('../src/db/pool.js');
const app = await buildApp({ logger: false });
await app.ready();
const call = async (m, u, token, body) => { const r = await app.inject({ method: m, url: `/api/v1${u}`, payload: body, headers: token ? { authorization: `Bearer ${token}` } : {} }); return r.json(); };
const tk = (await call('POST', '/auth/login', null, { email: DEMO.email, password: DEMO.password })).accessToken;
const open = (await call('GET', '/tickets?status=open&sort=frustration&limit=1', tk)).tickets[0];
const cust = (await call('GET', '/customers', tk)).customers;
const agent = (await call('GET', '/members', tk)).members.find((m) => m.role === 'agent');
const show = (n, v) => console.log(`\n== ${n}\n${JSON.stringify(v, null, 0).slice(0, 700)}`);
show('26 triage', await call('POST', '/intel/triage/priority', tk, { title: 'Erreur 502 lors du paiement', body: 'Le paiement echoue en production, urgent' }));
show('27 eta', await call('GET', `/intel/tickets/${open.id}/eta`, tk));
show('28 health', (({ series, ...r }) => r)(await call('GET', `/intel/customers/${cust[0].id}/health`, tk)));
show('29 assign', (await call('POST', '/intel/assign/recommend', tk, { ticketId: open.id })).ranking);
show('30 topics', (await call('GET', '/intel/topics', tk)).topics.map((t) => [t.size, t.terms.join(',')]));
show('31 backlog', await call('GET', '/intel/backlog/forecast', tk));
show('32 dup clusters', (await call('GET', '/intel/duplicates/clusters', tk)).clusters.map((c) => [c.primary.key, c.size]));
show('33 effort', (await call('GET', '/intel/effort', tk)).tickets.slice(0, 3));
show('34 coaching', await call('GET', `/intel/agents/${agent.id}/coaching`, tk));
show('35 stale', (await call('GET', '/intel/stale', tk)).stale.slice(0, 4));
show('36 capacity', await call('GET', '/intel/capacity/forecast', tk));
show('37 coverage gaps', (({ grid, ...r }) => r)(await call('GET', '/intel/coverage/gaps', tk)));
show('38 kb impact', await call('GET', '/intel/kb/impact', tk));
show('39 deploy risk', await call('GET', '/intel/deploys/risk?component=checkout', tk));
show('40 lead-lag', await call('GET', '/intel/components/lead-lag', tk));
show('41 segments', (await call('GET', '/intel/customers/segments', tk)).segments?.map((s) => [s.code, s.size, s.averageTone]));
show('42 next best', (await call('GET', '/intel/next-best', tk)).items.slice(0, 3));
show('43 macros', await call('GET', '/intel/macros', tk));
show('44 tone', await call('GET', `/intel/tickets/${open.id}/tone-shift`, tk));
show('45 summary', await call('GET', `/intel/tickets/${open.id}/summary`, tk));
show('46 bus', await call('GET', '/intel/team/bus-factor', tk));
show('47 fairness', await call('GET', '/intel/fairness', tk));
show('48 pii audit', await call('GET', '/intel/pii/audit', tk));
await app.close(); await pool.end();
